#!/usr/bin/env bash
#
# llm-git-commit -- build entry point. `bash compile.sh` is the ONE build command.
#
# There is NO native freeze step. Inference runs from a Python venv (llama-cpp-python
# loads a bundled libllama.so via ctypes; a Nuitka --onefile cannot carry that cleanly,
# so we ship the venv and deliver thin launchers instead). This script:
#   1. self-bootstraps venv/ and installs requirements.txt into it (the CPU wheel
#      index is an --extra-index-url, so nothing is compiled -- no cmake/gcc),
#   2. writes the two delivered executables into output/ (the artifact dir, like qvm):
#        * output/git             -- the git shim (a bare `git commit` -> local-model
#                                    subject; everything else passes through to real git),
#        * output/llm-git-commit  -- the tool's own CLI (also does `--uninstall`).
#      Both are self-contained launchers that re-exec THIS checkout's venv + libraries/,
#      so they keep working after `sudo install`. Keep the repo here.
#
# Install them the standard way (see README). The git shim must NOT replace
# /usr/bin/git. /usr/local/bin is earlier on PATH, so the shim shadows git there:
#   sudo install -m 755 output/git            /usr/local/bin/
#   sudo install -m 755 output/llm-git-commit /usr/bin/
#   sudo install -m 644 libraries/completion.bash /usr/share/bash-completion/completions/llm-git-commit
#
# Requires (system): python, python-pip (see packages_x86_64). Self-bootstrapping like
# tests.sh: a fresh checkout runs `bash download_llm.sh` first, then `bash compile.sh`.
# The model download is not part of this script.

set -o errexit
set -o nounset
set -o pipefail

REPODIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPODIR"

OUTDIR="$REPODIR/output"
LOGDIR="$REPODIR/logs"
LOG="$LOGDIR/compile.log"
VENV="$REPODIR/venv"
PY="$VENV/bin/python"
REQ="$REPODIR/requirements.txt"
STAMP="$VENV/.requirements.installed"
CPU_INDEX="https://abetlen.github.io/llama-cpp-python/whl/cpu"
mkdir -p "$OUTDIR" "$LOGDIR"

export PYTHONDONTWRITEBYTECODE=1

# Stopwatch: format a whole-second duration as e.g. "7m 32s" / "12s".
_format_duration() {
    local secs=$1 m s
    m=$(( secs / 60 )); s=$(( secs % 60 ))
    if [ "$m" -gt 0 ]; then printf '%dm %02ds' "$m" "$s"; else printf '%ds' "$s"; fi
}
_COMPILE_START="$(date +%s)"
: > "$LOG"
_report() {
    local rc=$? elapsed line
    elapsed=$(( $(date +%s) - _COMPILE_START ))
    if [ "$rc" -eq 0 ]; then line="[time] Compile finished in $(_format_duration "$elapsed")."
    else                     line="[time] Compile FAILED after $(_format_duration "$elapsed") (exit $rc)."
    fi
    echo "$line"; echo "$line" >> "$LOG" 2>/dev/null || true
}
trap _report EXIT

# --- Self-bootstrap the venv (mirrors tests.sh) -------------------------------
if [ ! -x "$PY" ]; then
    BOOT="$(command -v python3 || true)"
    [ -n "$BOOT" ] || { echo "[compile] no python3 -- pacman -S python python-pip" | tee -a "$LOG" >&2; exit 1; }
    echo "[compile] creating venv at $VENV" | tee -a "$LOG"
    "$BOOT" -m venv "$VENV" >>"$LOG" 2>&1
fi

REQ_HASH=""
[ -f "$REQ" ] && REQ_HASH="$(sha256sum "$REQ" | cut -d' ' -f1)"
if [ ! -f "$STAMP" ] || [ "$(cat "$STAMP" 2>/dev/null)" != "$REQ_HASH" ]; then
    echo "[compile] installing requirements (prebuilt CPU wheel -- no compiler needed)" | tee -a "$LOG"
    _pip() {
        local out rc
        out="$("$PY" -m pip install --quiet "$@" 2>&1)"; rc=$?
        printf '%s\n' "$out" >> "$LOG" 2>/dev/null || true
        [ "$rc" -ne 0 ] && { echo "[compile] pip install failed (exit $rc):" >&2; printf '%s\n' "$out" >&2; }
        return "$rc"
    }
    _pip --upgrade pip
    [ -f "$REQ" ] && _pip --extra-index-url "$CPU_INDEX" -r "$REQ"
    echo "$REQ_HASH" > "$STAMP"
fi

# Safety net: the heavy import must work before we deliver launchers that depend on it.
if ! "$PY" -c "import llama_cpp" >>"$LOG" 2>&1; then
    echo "[compile] llama_cpp not importable -- see $LOG" | tee -a "$LOG" >&2
    exit 1
fi

# --- Deliver the launchers into output/ ---------------------------------------
# Each is a tiny shell stub that runs THIS venv's python against libraries/. They are
# the delivered artifacts; `sudo install` copies them into place (see README).
_emit() {                    # $1 = output path, $2 = entry module, $3 = entry call
    local dest="$1" module="$2" call="$3"
    cat > "$dest" <<EOF
#!/usr/bin/env bash
# Generated by llm-git-commit/compile.sh -- do not edit; re-run compile.sh.
# python -c sets argv[0] to "-c", so record this launcher's path. The shim drops
# that directory from PATH and execs the real git instead of itself.
# -P keeps the repo's cwd off sys.path. Otherwise a file named math.py or
# random.py in the repository shadows the standard library and the model fails.
export LLM_GIT_COMMIT_SHIM="\$(readlink -f "\$0")"
exec "$PY" -P -c 'import sys; sys.path.insert(0, "$REPODIR/libraries"); import $module; sys.exit($call)' "\$@"
EOF
    chmod 755 "$dest"
}

_emit "$OUTDIR/git"            git_shim                "git_shim.main()"
_emit "$OUTDIR/llm-git-commit" command_line_interface  "command_line_interface.main()"

echo "[compile] built output/git and output/llm-git-commit" | tee -a "$LOG"
echo "[compile] install them: see README (sudo install -m 755 output/git /usr/local/bin/)" | tee -a "$LOG"
echo "[compile] done." | tee -a "$LOG"
