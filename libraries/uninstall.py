"""uninstall.py - remove what llm-git-commit put on the machine.

`llm-git-commit --uninstall` removes:

  * the `git` shim and the `llm-git-commit` command, only when the file still
    carries compile.sh's marker (a real git is never deleted),
  * the bash completion,
  * the downloaded GGUF: the Hugging Face repo dir, the blob it points at, and
    this checkout's cache/,
  * this checkout's venv/.

The source checkout stays. `sudo` looks in the invoking user's home, because
sudo would otherwise clean /root and leave the gigabyte model where it is.
"""

from __future__ import annotations

import os
import pwd
import shutil
from pathlib import Path

import configuration

# The marker compile.sh writes into every launcher it generates. Presence of this
# line is what proves a file on PATH is OUR stub and therefore safe to remove.
_MARKER = "Generated by llm-git-commit/"

_LAUNCHERS = ("git", "llm-git-commit")
_COMPLETION_NAME = "llm-git-commit"

# Filled by _remove when a path needs root. run() turns that into exit 1.
_denied: list[str] = []


def _bin_dirs() -> list[str]:
    """Install prefixes plus every directory on PATH."""
    dirs = ["/usr/bin", "/usr/local/bin", os.path.expanduser("~/.local/bin")]
    for part in os.environ.get("PATH", "").split(os.pathsep):
        if part and part not in dirs:
            dirs.append(part)
    return dirs


def _completion_dirs() -> list[str]:
    return [
        "/usr/share/bash-completion/completions",
        "/usr/local/share/bash-completion/completions",
        os.path.expanduser("~/.local/share/bash-completion/completions"),
    ]


def _homes() -> list[Path]:
    """Homes that may hold the model. sudo's own home is /root, which is wrong."""
    homes: list[Path] = []
    sudo_user = os.environ.get("SUDO_USER", "").strip()
    if sudo_user and sudo_user != "root":
        try:
            homes.append(Path(pwd.getpwnam(sudo_user).pw_dir))
        except (KeyError, OSError):
            pass
    home = Path.home()
    if home not in homes:
        homes.append(home)
    return homes


def _checkout() -> Path:
    """This repo. uninstall.py lives in libraries/, so the checkout is its parent."""
    return Path(__file__).resolve().parents[1]


def _repos() -> list[str]:
    repos = list(configuration.KNOWN_REPOS)
    extra = os.environ.get("LLM_GIT_COMMIT_REPO", "").strip()
    if extra and extra not in repos:
        repos.append(extra)
    return repos


def _is_our_launcher(path: str) -> bool:
    """True only when `path` is a regular file containing our marker line."""
    try:
        if not os.path.isfile(path):
            return False
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return _MARKER in fh.read(4096)
    except OSError:
        return False


def _remove(path: str, *, must_be_ours: bool) -> int:
    """Remove a file. Returns 1 if it was removed. Real git fails the marker check."""
    if must_be_ours and not _is_our_launcher(path):
        return 0
    if not os.path.lexists(path):
        return 0
    try:
        os.remove(path)
        print(f"  removed {path}")
        return 1
    except PermissionError:
        _denied.append(path)
        print(f"  need root: sudo rm {path}")
        return 0
    except OSError as exc:
        print(f"  could not remove {path}: {exc}")
        return 0


def _rmtree(path: Path) -> int:
    """Remove a file or directory. Returns 1 if something was removed."""
    if not path.exists() and not path.is_symlink():
        return 0
    try:
        if path.is_symlink() or path.is_file():
            path.unlink()
        else:
            shutil.rmtree(path)
        print(f"  removed {path}")
        return 1
    except PermissionError:
        _denied.append(str(path))
        print(f"  need root: sudo rm -rf {path}")
        return 0
    except OSError as exc:
        print(f"  could not remove {path}: {exc}")
        return 0


def _remove_launchers() -> int:
    removed = 0
    for directory in _bin_dirs():
        for name in _LAUNCHERS:
            removed += _remove(os.path.join(directory, name), must_be_ours=True)
    return removed


def _remove_completions() -> int:
    removed = 0
    for directory in _completion_dirs():
        removed += _remove(os.path.join(directory, _COMPLETION_NAME), must_be_ours=False)
    return removed


def _blob_targets(model_dir: Path, hub: Path) -> list[Path]:
    """Real files the snapshot symlinks point at, limited to this hub's blobs/."""
    blobs_root = hub / "blobs"
    found: list[Path] = []
    if not model_dir.is_dir():
        return found
    for path in model_dir.rglob("*"):
        if not path.is_symlink():
            continue
        try:
            target = path.resolve(strict=True)
        except OSError:
            continue
        try:
            target.relative_to(blobs_root)
        except ValueError:
            continue
        if target.is_file():
            found.append(target)
    return found


def _drop_model(hub: Path, repo: str) -> int:
    """Delete one downloaded repo, its lock, and the blob the snapshot points at."""
    name = "models--" + repo.replace("/", "--")
    model_dir = hub / name
    blobs = _blob_targets(model_dir, hub)
    removed = _rmtree(model_dir)
    removed += _rmtree(hub / ".locks" / name)
    for blob in blobs:
        # The blob, plus the hub's .lock and .refs siblings next to it.
        for extra in blob.parent.glob(blob.name + "*"):
            removed += _remove(str(extra), must_be_ours=False)
        parent = blob.parent
        try:
            if parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
        except OSError:
            pass
    return removed


def _drop_orphan_blob_meta(hub: Path) -> int:
    """Remove .lock/.refs left behind after the blob itself is gone."""
    blobs = hub / "blobs"
    if not blobs.is_dir():
        return 0
    removed = 0
    for meta in list(blobs.rglob("*")):
        if not meta.is_file():
            continue
        if not (meta.name.endswith(".lock") or meta.name.endswith(".refs")):
            continue
        stem = meta.name.rsplit(".", 1)[0]
        if (meta.parent / stem).exists():
            continue
        removed += _remove(str(meta), must_be_ours=False)
        parent = meta.parent
        try:
            if parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
        except OSError:
            pass
    return removed


def _remove_models() -> int:
    removed = 0
    for home in _homes():
        hub = home / ".cache" / "huggingface" / "hub"
        if hub.is_dir():
            for repo in _repos():
                removed += _drop_model(hub, repo)
            removed += _drop_orphan_blob_meta(hub)
        removed += _rmtree(home / ".cache" / "huggingface" / "xet")
    root = _checkout()
    removed += _rmtree(root / "cache")
    return removed


def _remove_venv() -> int:
    return _rmtree(_checkout() / "venv")


def run() -> int:
    """Remove installed files, the model, and the venv. The source tree stays."""
    global _denied
    _denied = []
    removed = (
        _remove_launchers()
        + _remove_completions()
        + _remove_models()
        + _remove_venv()
    )
    if removed == 0 and not _denied:
        print("Nothing to uninstall.")
    else:
        print(f"Removed {removed} item(s).")
    print("The source checkout is still here. A real git is never removed.")
    if _denied:
        print("Re-run as root for the rest: sudo llm-git-commit --uninstall")
        return 1
    return 0
