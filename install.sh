#!/usr/bin/env bash
#
# llm-git-commit -- install entry point. `bash install.sh` is the ONE command.
#
# There is NO compile step: inference runs from a Python venv (the llama-cpp-python
# CPU wheel loads a bundled libllama.so via ctypes -- freezing it with Nuitka is
# pure pain for no gain, so we ship the venv instead). This script:
#   1. builds cache/venv and installs requirements.txt (the CPU wheel index is
#      passed as an --extra-index-url so nothing is compiled -- no cmake/gcc),
#   2. installs two launchers into $PREFIX/bin (default /usr/local/bin, which
#      precedes /usr/bin on PATH):
#        * git              -- the shim: a bare `git commit` writes the subject with
#                              the local model; everything else passes through.
#        * llm-git-commit   -- the tool's own CLI (what the shim calls).
#   3. installs bash completion for `llm-git-commit`.
#
# The launchers point at THIS checkout (its venv + libraries/), so keep the repo in
# place after installing. Re-run this script after moving it.
#
# PREFIX overrides the install root:  PREFIX=$HOME/.local bash install.sh
# (ensure $PREFIX/bin precedes /usr/bin on PATH, or the git shim won't intercept).

set -o errexit
set -o nounset
set -o pipefail

REPODIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$REPODIR"

PREFIX="${PREFIX:-/usr/local}"
BINDIR="$PREFIX/bin"
VENV="$REPODIR/cache/venv"
PY="$VENV/bin/python"
REQ="$REPODIR/requirements.txt"
STAMP="$VENV/.requirements.installed"
CPU_INDEX="https://abetlen.github.io/llama-cpp-python/whl/cpu"

export PYTHONDONTWRITEBYTECODE=1

# --- venv ---------------------------------------------------------------------
if [ ! -x "$PY" ]; then
    BOOT="$(command -v python3 || true)"
    [ -n "$BOOT" ] || { echo "[install] no python3 -- sudo pacman -S python python-pip" >&2; exit 1; }
    echo "[install] creating venv at $VENV"
    "$BOOT" -m venv "$VENV"
fi

# Install requirements only when they change (stamp = hash of requirements.txt).
REQ_HASH=""
[ -f "$REQ" ] && REQ_HASH="$(sha256sum "$REQ" | cut -d' ' -f1)"
if [ ! -f "$STAMP" ] || [ "$(cat "$STAMP" 2>/dev/null)" != "$REQ_HASH" ]; then
    echo "[install] installing requirements (prebuilt CPU wheel -- no compiler needed)"
    "$PY" -m pip install --quiet --upgrade pip
    "$PY" -m pip install --quiet --extra-index-url "$CPU_INDEX" -r "$REQ"
    echo "$REQ_HASH" > "$STAMP"
fi

# Safety net: the two heavy imports must work before we wire up the launchers.
if ! "$PY" -c "import llama_cpp, huggingface_hub" 2>/dev/null; then
    echo "[install] llama_cpp / huggingface_hub not importable after install -- aborting." >&2
    exit 1
fi

# --- launchers ----------------------------------------------------------------
# Each is a tiny shell stub that runs THIS venv's python against libraries/. The
# git shim dispatches through git_shim.py; the CLI through command_line_interface.
_write_launcher() {          # $1 = dest path, $2 = entry module, $3 = entry call
    local dest="$1" module="$2" call="$3"
    local tmp; tmp="$(mktemp)"
    cat > "$tmp" <<EOF
#!/usr/bin/env bash
# Generated by llm-git-commit/install.sh -- do not edit; re-run install.sh.
exec "$PY" -c 'import sys; sys.path.insert(0, "$REPODIR/libraries"); import $module; sys.exit($call)' "\$@"
EOF
    _install_file 755 "$tmp" "$dest"
    rm -f "$tmp"
}

# install to $BINDIR, using sudo only if we cannot write there directly.
_install_file() {            # $1 = mode, $2 = src, $3 = dest
    local mode="$1" src="$2" dest="$3"
    if [ -w "$(dirname "$dest")" ] || [ -w "$dest" ] 2>/dev/null; then
        install -m "$mode" "$src" "$dest"
    else
        echo "[install] writing $dest (needs sudo)"
        sudo install -m "$mode" "$src" "$dest"
    fi
}

mkdir -p "$BINDIR" 2>/dev/null || sudo mkdir -p "$BINDIR"
_write_launcher "$BINDIR/git"            git_shim                  "git_shim.main()"
_write_launcher "$BINDIR/llm-git-commit" command_line_interface    "command_line_interface.main()"

# bash completion for the CLI (the git shim rides git's own completion).
COMP_DIR="/usr/share/bash-completion/completions"
if [ -d "$COMP_DIR" ] || [ -d "$(dirname "$COMP_DIR")" ]; then
    _install_file 644 "$REPODIR/libraries/completion.bash" "$COMP_DIR/llm-git-commit" || true
fi

echo "[install] done."
echo "[install]   git shim : $BINDIR/git  ->  real git resolves to $( "$PY" - <<'PY'
import os, shutil, sys
self=os.path.abspath("$BINDIR")
parts=[p for p in os.environ.get("PATH","").split(os.pathsep) if p and os.path.abspath(p)!=self]
print(shutil.which("git", path=os.pathsep.join(parts)) or "NONE")
PY
)"
echo "[install]   CLI      : $BINDIR/llm-git-commit"
echo "[install] ensure $BINDIR precedes /usr/bin on PATH, then: git add -p && git commit"
