"""uninstall removes our files and the model, and leaves a real git alone."""

from __future__ import annotations

from pathlib import Path

import uninstall


def test_uninstall_removes_shim_model_blob_and_venv(tmp_path, monkeypatch, capsys):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    real = bin_dir / "git"
    real.write_text("#!/bin/sh\n# real git\n")
    ours = bin_dir / "llm-git-commit"
    ours.write_text("# Generated by llm-git-commit/compile.sh\n")

    comp = tmp_path / "comp"
    comp.mkdir()
    (comp / "llm-git-commit").write_text("# completion\n")

    hub = tmp_path / "home" / ".cache" / "huggingface" / "hub"
    blob = hub / "blobs" / "6c" / "deadbeef"
    blob.parent.mkdir(parents=True)
    blob.write_bytes(b"gguf-bytes")
    Path(str(blob) + ".refs").write_text("refs")
    Path(str(blob) + ".lock").write_text("")
    snap = hub / "models--Qwen--Qwen2.5-1.5B-Instruct-GGUF" / "snapshots" / "rev"
    snap.mkdir(parents=True)
    (snap / "qwen2.5-1.5b-instruct-q4_k_m.gguf").symlink_to(blob)
    lock = hub / ".locks" / "models--Qwen--Qwen2.5-1.5B-Instruct-GGUF"
    lock.mkdir(parents=True)
    (lock / "x").write_text("l")
    orphan = hub / "blobs" / "ab" / "abc.refs"
    orphan.parent.mkdir(parents=True)
    orphan.write_text("old")

    checkout = tmp_path / "checkout"
    (checkout / "venv").mkdir(parents=True)
    (checkout / "venv" / "py").write_text("x")
    (checkout / "cache" / "model").mkdir(parents=True)
    (checkout / "cache" / "model" / "m.gguf").write_bytes(b"m")
    (checkout / "README.md").write_text("keep me")

    monkeypatch.setattr(uninstall, "_bin_dirs", lambda: [str(bin_dir)])
    monkeypatch.setattr(uninstall, "_completion_dirs", lambda: [str(comp)])
    monkeypatch.setattr(uninstall, "_homes", lambda: [tmp_path / "home"])
    monkeypatch.setattr(uninstall, "_checkout", lambda: checkout)

    assert uninstall.run() == 0
    assert real.is_file()
    assert not ours.exists()
    assert not (comp / "llm-git-commit").exists()
    assert not blob.exists()
    assert not Path(str(blob) + ".refs").exists()
    assert not Path(str(blob) + ".lock").exists()
    assert not orphan.exists()
    assert not (hub / "models--Qwen--Qwen2.5-1.5B-Instruct-GGUF").exists()
    assert not lock.exists()
    assert not (checkout / "venv").exists()
    assert not (checkout / "cache").exists()
    assert (checkout / "README.md").read_text() == "keep me"
    out = capsys.readouterr().out
    assert "untouched" not in out
    assert "source checkout is still here" in out


def test_sudo_home_is_the_invoking_user(tmp_path, monkeypatch):
    user_home = tmp_path / "main"
    user_home.mkdir()

    class _Pass:
        pw_dir = str(user_home)

    monkeypatch.setenv("SUDO_USER", "main")
    monkeypatch.setattr(uninstall.pwd, "getpwnam", lambda name: _Pass())
    homes = uninstall._homes()
    assert homes[0] == user_home
